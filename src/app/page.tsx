import Image from "next/image";
import Link from "next/link";
import { headers } from "next/headers";
import { connection } from "next/server";
import { Translator } from "@/components/translator";
import { getPublicConfig } from "@/lib/server/config";

const NOTICE_BY_MODE = {
  demo: "Demo mode: no model is called. Pick an example to see a sample rewrite.",
  disabled: "Translation is temporarily unavailable. Please check back later.",
} as const;

const REGION_BANNER =
  "Live generation is not available in your region from this network. Examples are prewritten; nothing you type is sent.";

export default async function Home() {
  await connection();
  const headerList = await headers();
  const rawHost =
    headerList.get("x-forwarded-host")?.split(",")[0]?.trim() ||
    headerList.get("host") ||
    "";
  // Strip any port (and bracket handling for IPv6) the same way the API
  // route does, by parsing the host as a URL authority.
  let hostname = "";
  try {
    hostname = new URL(`http://${rawHost}`).hostname;
  } catch {
    hostname = "";
  }

  const config = getPublicConfig({
    headers: headerList,
    hostname,
  });

  const publicConfig = {
    mode: config.mode,
    liveAvailability: config.liveAvailability,
    notice: config.notice,
    limits: config.limits,
  };

  const bannerText =
    config.mode === "live" && config.liveAvailability === "region"
      ? REGION_BANNER
      : config.mode === "live"
        ? `Live: rewrites are generated by ${config.modelLabel}. Acknowledge the notice below to translate.`
        : NOTICE_BY_MODE[config.mode];

  const bannerLabel =
    config.mode === "live" && config.liveAvailability === "region"
      ? "region"
      : config.mode;

  return (
    <div className="mx-auto flex min-h-screen max-w-6xl flex-col px-4 py-8 sm:px-6 lg:py-12">
      <header className="mb-8">
        <h1>
          <Image
            src="/brand/mimus-logo.png"
            alt="Mimus"
            width={720}
            height={210}
            priority
            className="block h-10 w-auto sm:h-12 md:h-14"
          />
        </h1>
        <p className="mt-2 text-xl text-accent-strong">
          Translate meaning, not just words.
        </p>
        <p className="mt-3 max-w-2xl leading-relaxed text-ink-soft">
          Mimus rewrites English writing styles: Human, LinkedIn Speak,
          Corporate, Startup Founder, and Academic. It does not translate
          between languages. Say it plainly, then hear how it would sound in
          another style, or translate it back.
        </p>
        <p
          data-testid="availability"
          className="mt-5 inline-block max-w-2xl rounded-lg border border-line bg-white px-4 py-2 text-sm leading-relaxed text-ink"
        >
          <strong className="font-semibold uppercase tracking-wide">
            {bannerLabel}
          </strong>{" "}
          — {bannerText}
        </p>
      </header>

      <main className="flex-1">
        <Translator config={publicConfig} />
      </main>

      <footer className="mt-12 border-t border-line pt-6 text-sm text-ink-soft">
        <p className="flex flex-wrap gap-x-4 gap-y-2">
          <a
            className="inline-flex min-h-11 items-center font-medium text-accent-strong underline underline-offset-4"
            href="https://github.com/edumarcano/mimus"
          >
            Source on GitHub
          </a>
          <Link
            href="/privacy"
            className="inline-flex min-h-11 items-center font-medium text-accent-strong underline underline-offset-4"
          >
            Privacy
          </Link>
        </p>
        <p className="mt-1 max-w-2xl">
          Mimus is an independent project. It is not affiliated with or endorsed
          by LinkedIn.
        </p>
      </footer>
    </div>
  );
}
